# Delivery Route Optimizer (Capacitated VRP) - Portfolio Project #1
# Run in Google Colab. First cell:  !pip install ortools folium
import math, random
from ortools.constraint_solver import pywrapcp, routing_enums_pb2
import folium

# ---------- 1. Problem data (synthetic, around Delhi/NCR) ----------
random.seed(42)
N_CUSTOMERS = 40
DEPOT = (28.6139, 77.2090)
pts = [DEPOT] + [(random.uniform(28.45, 28.75), random.uniform(77.05, 77.40))
                 for _ in range(N_CUSTOMERS)]
demand = [0] + [random.randint(1, 10) for _ in range(N_CUSTOMERS)]  # parcels per stop

NUM_VEHICLES = 10
CAPACITY = 60                 # parcels per vehicle
COST_PER_KM = 12              # Rs fuel + wear per km (assumption, change it)
DRIVER_COST_PER_ROUTE = 1000  # Rs per vehicle per day (assumption)
WORKING_DAYS = 26

# ---------- 2. Distance matrix (haversine x 1.3 road factor, in metres) ----------
def road_km(a, b):
    R = 6371
    la1, lo1, la2, lo2 = map(math.radians, (*a, *b))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * R * math.asin(math.sqrt(h)) * 1.3

dist = [[int(road_km(a, b) * 1000) for b in pts] for a in pts]

# ---------- 3. Baseline: how a manual planner might do it (fill vans in order) ----------
def baseline_routes():
    order = sorted(range(1, len(pts)),
                   key=lambda i: math.atan2(pts[i][0] - DEPOT[0], pts[i][1] - DEPOT[1]))
    routes, cur, load = [], [], 0
    for i in order:
        if load + demand[i] > CAPACITY:
            routes.append(cur); cur, load = [], 0
        cur.append(i); load += demand[i]
    routes.append(cur)
    return routes

# ---------- 4. Optimized: OR-Tools ----------
manager = pywrapcp.RoutingIndexManager(len(pts), NUM_VEHICLES, 0)
routing = pywrapcp.RoutingModel(manager)

def distance_cb(i, j):
    return dist[manager.IndexToNode(i)][manager.IndexToNode(j)]
transit = routing.RegisterTransitCallback(distance_cb)
routing.SetArcCostEvaluatorOfAllVehicles(transit)
# Using a vehicle has a cost (driver), expressed in metre-equivalents
routing.SetFixedCostOfAllVehicles(int(DRIVER_COST_PER_ROUTE / COST_PER_KM * 1000))

def demand_cb(i):
    return demand[manager.IndexToNode(i)]
dem = routing.RegisterUnaryTransitCallback(demand_cb)
routing.AddDimensionWithVehicleCapacity(dem, 0, [CAPACITY] * NUM_VEHICLES, True, "Capacity")

params = pywrapcp.DefaultRoutingSearchParameters()
params.first_solution_strategy = routing_enums_pb2.FirstSolutionStrategy.PATH_CHEAPEST_ARC
params.local_search_metaheuristic = routing_enums_pb2.LocalSearchMetaheuristic.GUIDED_LOCAL_SEARCH
params.time_limit.seconds = 20
solution = routing.SolveWithParameters(params)

opt_routes = []
for v in range(NUM_VEHICLES):
    idx, r = routing.Start(v), []
    while not routing.IsEnd(idx):
        n = manager.IndexToNode(idx)
        if n != 0:
            r.append(n)
        idx = solution.Value(routing.NextVar(idx))
    if r:
        opt_routes.append(r)

# ---------- 5. Before vs after (the numbers clients pay for) ----------
def daily_cost(routes):
    km = sum(route_km(r) for r in routes)
    return km, km * COST_PER_KM + len(routes) * DRIVER_COST_PER_ROUTE

b_km, b_cost = daily_cost(baseline_routes())
o_km, o_cost = daily_cost(opt_routes)
print(f"BEFORE: {len(baseline_routes())} vehicles, {b_km:.0f} km/day, Rs {b_cost:,.0f}/day")
print(f"AFTER : {len(opt_routes)} vehicles, {o_km:.0f} km/day, Rs {o_cost:,.0f}/day")
print(f"Saving: {100*(b_cost-o_cost)/b_cost:.1f}%  =  Rs {(b_cost-o_cost)*WORKING_DAYS:,.0f} per month")

# ---------- 6. Map ----------
colors = ["red", "blue", "green", "purple", "orange", "darkred", "cadetblue", "black", "pink", "gray"]
m = folium.Map(location=DEPOT, zoom_start=10)
folium.Marker(DEPOT, popup="Depot", icon=folium.Icon(color="black", icon="home")).add_to(m)
for k, r in enumerate(opt_routes):
    path = [DEPOT] + [pts[i] for i in r] + [DEPOT]
    folium.PolyLine(path, color=colors[k % len(colors)], weight=3).add_to(m)
    for i in r:
        folium.CircleMarker(pts[i], radius=4, color=colors[k % len(colors)], fill=True,
                            popup=f"Stop {i}, load {demand[i]}").add_to(m)

import matplotlib.pyplot as plt

plt.figure(figsize=(8, 8))
for k, r in enumerate(opt_routes):
    path = [DEPOT] + [pts[i] for i in r] + [DEPOT]
    plt.plot([p[1] for p in path], [p[0] for p in path], marker="o", label=f"Vehicle {k+1}")
plt.scatter(DEPOT[1], DEPOT[0], c="black", s=200, marker="*", zorder=5, label="Depot")
plt.title("Optimized delivery routes (40 stops, Delhi/NCR)")
plt.xlabel("Longitude"); plt.ylabel("Latitude")
plt.legend(); plt.grid(alpha=0.3)
plt.savefig("map.png", dpi=150, bbox_inches="tight")
plt.show()